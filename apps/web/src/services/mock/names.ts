export interface GeneratedName {
  name: string;
  symbol: string;
}

export function generateTokenName(rng: Rng): GeneratedName {
  const noun = rng.pick(NOUNS);
  const usePrefix = rng.chance(0.6);
  const prefix = usePrefix ? rng.pick(PREFIXES) : "";
  const suffix = rng.pick(SUFFIXES);
  const name = `${prefix ? `${prefix} ` : ""}${noun}${suffix}`.trim();
  let symbol: string;
  const style = rng.next();
  if (style < 0.35) symbol = noun.toUpperCase();
  else if (style < 0.6 && prefix) symbol = `${prefix[0]}${noun}`.toUpperCase();
  else if (style < 0.8) symbol = `${prefix}${noun}`.toUpperCase();
  else symbol = `${noun.toUpperCase()}${rng.int(1, 99)}`;
  symbol = symbol.replace(/[^A-Z0-9]/g, "").slice(0, 9) || "MEME";
  return { name, symbol };
}

