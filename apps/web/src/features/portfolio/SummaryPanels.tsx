export type PnlRange = "7d" | "30d" | "max";

export const RANGE_LABEL: Record<PnlRange, string> = { "7d": "7d", "30d": "30d", max: "Max" };

const DAY_MS = 86_400_000;
const RANGE_MS: Record<PnlRange, number> = { "7d": 7 * DAY_MS, "30d": 30 * DAY_MS, max: Number.POSITIVE_INFINITY };

/*
 * Balance module. Anatomy follows Binance's "Estimated Balance" (headline value, fiat
 * equivalent underneath) https://mobbin.com/screens/5acd0f5e-9019-4e1f-95e1-1446bbccd036 with
 * Kraken Pro's label/value rows https://mobbin.com/screens/fe204312-8607-4018-b0dd-a36dc71f4978
 */
export function BalancePanel({ status, solUsd, own }: { status: WalletStatus; solUsd: number; own: boolean }) {
  const openFund = useUi((s) => s.openFund);
  const { positionsValue, openCount, unrealized } = useMemo(() => {
    let value = 0;
    let pnl = 0;
    let count = 0;
    for (const p of status.positions) {
      if (p.closed) continue;
      value += p.valueSol;
      pnl += p.unrealizedPnlSol;
      count++;
    }
    return { positionsValue: value, openCount: count, unrealized: pnl };
  }, [status.positions]);
  const total = status.solBalance + positionsValue;
  const available = Math.max(0, status.solBalance - status.reservedSol);

  return (
    <Panel
      title="Balance"
      extra={
        own ? (
          <>
            <Button size="xs" variant="ghost" onClick={() => openFund("fund")}>
              Fund
            </Button>
            <Button size="xs" variant="ghost" onClick={() => openFund("withdraw")}>
              Withdraw
            </Button>
          </>
        ) : null
      }
    >
      <div className="flex flex-col gap-3 p-3">
        <div>
          <div className="zf-label">Total value</div>
          <div className="mt-1 flex items-baseline gap-1">
            <span className="text-display-2 font-semibold">{fmtSol(total)}</span>
            <span className="text-data text-fg-2">SOL</span>
          </div>
          <div className="text-label text-fg-2">
            {fmtUsd(total * solUsd)}
            <span className="text-fg-3">
              {" "}
              · {fmtSol(positionsValue)} SOL in {openCount} position{openCount === 1 ? "" : "s"}
            </span>
          </div>
        </div>
        <dl className="flex flex-col text-label">
          <StatRow label="Unrealized PnL">
            <span className={pnlTone(unrealized)}>{fmtSignedSol(unrealized)} SOL</span>
            <span className="text-fg-3">{fmtSignedUsd(unrealized * solUsd)}</span>
          </StatRow>
          <StatRow label="Available balance">
            <span>{fmtSol(available)} SOL</span>
            <span className="text-fg-3">{fmtUsd(available * solUsd)}</span>
          </StatRow>
          {own && (
            <StatRow label="Reserved by armed orders">
              <Link to="/orders" className="hover:underline" title="SOL held back for pre-signed buys, tips and fees">
                {fmtSol(status.reservedSol)} SOL
              </Link>
            </StatRow>
          )}
        </dl>
      </div>
    </Panel>
  );
}

/*
 * PnL module: cumulative daily PnL for the selected period. Chart placement follows the PnL
 * chart beside Binance's copy-trading performance block
 * https://mobbin.com/screens/b92a460e-23dc-40d5-8a9b-cd79d8eb9b7d
 */
export function PnlPanel({
  points,
  loading,
  range,
  className,
}: {
  points: PnlPoint[] | null;
  loading: boolean;
  range: PnlRange;
  className?: string;
}) {
  const change = useMemo(() => {
    if (!points || points.length < 2) return null;
    const first = points[0];
    const last = points[points.length - 1];
    return first && last ? last.pnlSol - first.pnlSol : null;
  }, [points]);
  const empty = points !== null && points.length === 0;

  return (
    <Panel
      title="PnL"
      className={className}
      bodyClassName="relative min-h-44"
      extra={
        <>
          {change !== null && (
            <span className={cn("text-label font-medium", pnlTone(change))}>
              {fmtSignedSol(change)} SOL <span className="font-normal text-fg-3">{RANGE_LABEL[range]}</span>
            </span>
          )}
          {getServices().simulated && (
            <span className="rounded-xs border border-hairline px-1 text-micro text-fg-3" title="Generated by the in-browser simulation">
              Simulated history
            </span>
          )}
        </>
      }
    >
      <PnlChart points={points} />
      {(points === null || empty) && (
        <div className="pointer-events-none absolute inset-0 flex items-center justify-center text-data text-fg-2">
          {points === null ? (loading ? "Loading PnL…" : "No PnL history") : "No PnL history yet"}
        </div>
      )}
    </Panel>
  );
}

interface Bucket {
  label: string;
  dot: string;
  test: (pct: number) => boolean;
}

/** Profitability ranges by (realized + unrealized) / bought. */
const BUCKETS: readonly Bucket[] = [
  { label: ">500%", dot: "bg-buy", test: (r) => r > 500 },
  { label: "200% – 500%", dot: "bg-buy/60", test: (r) => r > 200 },
  { label: "0% – 200%", dot: "bg-buy-tint-press", test: (r) => r >= 0 },
  { label: "0% – -50%", dot: "bg-sell/50", test: (r) => r >= -50 },
  { label: "< -50%", dot: "bg-sell", test: () => true },
];

/*
 * Performance module. Anatomy follows Binance's copy-trading "Performance" block (PnL, win
 * rate and position counts as label/value rows) https://mobbin.com/screens/b92a460e-23dc-40d5-8a9b-cd79d8eb9b7d
 * Positions and transactions are limited to the selected period (last trade inside it).
 */
export function PerformancePanel({
  positions,
  activity,
  solUsd,
  range,
}: {
  positions: Position[];
  activity: ActivityItem[];
  solUsd: number;
  range: PnlRange;
}) {
  const stats = useMemo(() => {
    const since = range === "max" ? Number.NEGATIVE_INFINITY : Date.now() - RANGE_MS[range];
    const counts = BUCKETS.map(() => 0);
    let totalPnl = 0;
    let closed = 0;
    let wins = 0;
    for (const p of positions) {
      if (p.lastTradeAt < since) continue;
      const pnl = positionPnl(p);
      totalPnl += pnl;
      if (p.closed && p.boughtSol > 0) {
        closed++;
        if (p.realizedPnlSol > 0) wins++;
      }
      if (!(p.boughtSol > 0)) continue;
      const pct = (pnl / p.boughtSol) * 100;
      const i = BUCKETS.findIndex((b) => b.test(pct));
      if (i >= 0) counts[i] = (counts[i] ?? 0) + 1;
    }
    let buys = 0;
    let sells = 0;
    for (const a of activity) {
      if (a.ts < since) continue;
      if (a.kind === "buy") buys++;
      else if (a.kind === "sell") sells++;
    }
    return { totalPnl, counts, classified: counts.reduce((s, n) => s + n, 0), closed, wins, buys, sells };
  }, [positions, activity, range]);

  return (
    <Panel title="Performance" extra={<span className="text-micro text-fg-3">{RANGE_LABEL[range]}</span>}>
      <div className="flex flex-col gap-3 p-3">
        <div className="grid grid-cols-2 gap-3">
          <div className="min-w-0">
            <div className="zf-label">Total PnL</div>
            <div className={cn("mt-1 truncate text-heading font-semibold", pnlTone(stats.totalPnl))}>
              {fmtSignedSol(stats.totalPnl)} SOL
            </div>
            <div className="text-label text-fg-3">{fmtSignedUsd(stats.totalPnl * solUsd)}</div>
          </div>
          <div className="min-w-0">
            <div className="zf-label">Total TXNS</div>
            <div className="mt-1 text-heading font-semibold">{fmtCount(stats.buys + stats.sells)}</div>
            <div className="text-label">
              <span className="text-buy">{fmtCount(stats.buys)}</span>
              <span className="text-fg-3"> / </span>
              <span className="text-sell">{fmtCount(stats.sells)}</span>
            </div>
          </div>
        </div>
        <ul className="flex flex-col text-label" aria-label="Positions by return">
          {BUCKETS.map((b, i) => (
            <li key={b.label} className="flex h-5 items-center justify-between gap-2">
              <span className="flex items-center gap-2 text-fg-2">
                <span className={cn("size-2 shrink-0 rounded-full", b.dot)} />
                {b.label}
              </span>
              <span className="font-medium">{fmtCount(stats.counts[i] ?? 0)}</span>
            </li>
          ))}
        </ul>
        <div className="flex h-1 overflow-hidden rounded-full bg-surface-3" aria-hidden="true">
          {stats.classified > 0 &&
            BUCKETS.map((b, i) => {
              const n = stats.counts[i] ?? 0;
              return n > 0 ? <div key={b.label} className={b.dot} style={{ width: `${(n / stats.classified) * 100}%` }} /> : null;
            })}
        </div>
        <div className="flex items-center justify-between text-label">
          <span className="text-fg-2" title="Share of closed positions that ended in profit">
            Win rate (closed)
          </span>
          <span>
            {stats.closed > 0 ? fmtPct((stats.wins / stats.closed) * 100) : "—"}
            <span className="text-fg-3">
              {" "}
              {fmtCount(stats.wins)}/{fmtCount(stats.closed)}
            </span>
          </span>
        </div>
      </div>
    </Panel>
  );
}
